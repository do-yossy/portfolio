// 各ブロックが偶然一致したペアでも、この1文で地域性と文面差を確保する。
function areaTail(areaLabel) {
  const ap = phrase(areaLabel);
  return [
    `※勤務地は${ap}周辺です。お住まいの地域や通勤についてもお気軽にご相談ください。`,
    `※${ap}周辺での募集です。ブランクのある方・未経験の方も歓迎しています。`,
    `※${ap}エリアでの勤務となります。まずはお気軽にご応募・お問い合わせください。`,
    `※勤務地は${ap}周辺。見学・お問い合わせだけでも大歓迎です。`,
  ][hashSeed(`tail|${areaLabel}`) % 4];
}

function build(familyKey, areaLabel) {
  const b = BUILDERS[familyKey];
  if (!b) throw new Error(`unknown family: ${familyKey}`);
  const r = b(areaLabel);
  r.description = `${r.description}\n\n${areaTail(areaLabel)}`;
  return r;
}

