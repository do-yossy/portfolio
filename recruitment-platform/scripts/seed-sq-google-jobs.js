const stmt = db.prepare(`
  INSERT OR IGNORE INTO jobs
    (id, title, location, salary, job_type, employment_type, description,
     tags, catchcopy, image_url, faq, is_published, target_media, published_at,
     company, rewarding, worktime_holiday, transportation, how_to_apply,
     created_at, updated_at)
  VALUES (?,?,?,?,?,?,?,?,?,?,?,1,'["google"]',?,?,?,?,?,?,?,?)
`);

let count = 0;
for (const j of JOBS) {
  try {
    stmt.run(
      crypto.randomUUID(),
      j.title,
      j.location,
      j.salary,
      COMMON.jobType,
      COMMON.employmentType,
      j.description,
      COMMON.tags,
      j.catchcopy || '',
      COMMON.imageUrl,
      COMMON.faq,
      now,       // published_at
      'sq',      // company
      j.rewarding || '',
      COMMON.holiday,
      COMMON.transportation,
      COMMON.howToApply,
      now,       // created_at
      now,       // updated_at
    );
    count++;
    console.log(`[${count}] 登録: ${j.title}`);
  } catch (e) {
    console.error(`エラー: ${j.title} →`, e.message);
  }
}

console.log(`\n完了: ${count}件の求人を登録しました`);
db.close();
