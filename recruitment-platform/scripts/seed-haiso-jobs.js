async function main() {
  console.log(`\n🚀 軽配送求人 ${JOBS.length}件 の登録を開始します...\n`);

  // 既存求人タイトルを取得して重複チェック
  const existing = await Jobs.findAll();
  const existingTitles = new Set(existing.map(j => j.title));

  let added = 0;
  let skipped = 0;

  for (const job of JOBS) {
    if (existingTitles.has(job.title)) {
      console.log(`  ⏭️  スキップ（既存）: ${job.title}`);
      skipped++;
      continue;
    }

    try {
      await Jobs.create({
        title:          job.title,
        location:       job.location,
        salary:         job.salary,
        jobType:        'ドライバー・配送',
        employmentType: '正社員',
        description:    job.description,
        tags:           job.tags,           // 配列で渡す（db.jsがJSON.stringifyする）
        catchcopy:      job.catchcopy,
        imageUrl:       '',
        faq:            job.faq,            // 配列で渡す（db.jsがJSON.stringifyする）
        isPublished:    true,
        publishedAt:    NOW,
        targetMedia:    TARGET_MEDIA,       // 配列で渡す
        company:        COMPANY,
      });
      console.log(`  ✅ 登録完了: ${job.title}`);
      added++;
    } catch (err) {
      console.error(`  ❌ 登録失敗: ${job.title}\n     ${err.message}`);
    }
  }

  console.log(`\n📊 結果: 登録 ${added}件 / スキップ ${skipped}件 / 合計 ${JOBS.length}件`);
  if (added > 0) {
    console.log('\n✅ 完了！管理画面 /admin/jobs で確認できます。');
    console.log('   Google しごと検索には /jobs/:id ページのJSON-LDが自動生成されます。');
  }
}

main().catch(err => {
  console.error('❌ エラー:', err.message);
  process.exit(1);
});
