function tipsFor(personaKey, gateNo) {
  const p = PERSONAS[personaKey];
  const t = GATE_TIPS[gateNo];
  if (!p || !t) return [];
  const out = [];
  if (p.aiBeginner) out.push({ tag: 'AIのコツ', text: t.ai });
  if (p.bizBeginner) out.push({ tag: '売るためのコツ', text: t.biz });
  if (!p.aiBeginner && !p.bizBeginner) out.push({ tag: '進め方', text: t.pro });
  return out;
}

function prepStepsFor(personaKey) {
  const p = PERSONAS[personaKey];
  if (!p) return [];
  return [...(p.aiBeginner ? PREP_STEPS.ai : []), ...(p.bizBeginner ? PREP_STEPS.biz : [])];
}

module.exports = { PERSONAS, tipsFor, prepStepsFor };
